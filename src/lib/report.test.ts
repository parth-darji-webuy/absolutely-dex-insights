import { describe, expect, it } from "vitest";
import { getReportRows } from "./data";
import { buildReport, csvText } from "./report";
import { vi } from "vitest";
import type { ReportRow } from "@/types";

const row: ReportRow = { date: "2026-10-07", weekday: "Wed", experiment: "Add to Cart button text", flag: "add-to-cart-btn", variant: "control", label: "Add to Cart", people: 120, converted: 12, ratePct: "10.00", metric: "added to cart" };
const FROM = new Date(2026, 9, 7);
const TO = new Date(2026, 9, 7);
const NOW = new Date(2026, 9, 28, 9, 5, 3);

describe("buildReport", () => {
  it("names the file after the experiment and the period", () => {
    expect(buildReport({ key: "add-to-cart", name: "Add to Cart" }, [row], FROM, TO, "Designer Exchange (Admin)", NOW).file).toBe("absolutelydex_add-to-cart-daily_2026-10-07.csv");
    expect(buildReport({ key: "add-to-cart", name: "Add to Cart" }, [row], FROM, new Date(2026, 9, 9), "x", NOW).file).toBe("absolutelydex_add-to-cart-daily_2026-10-07_to_2026-10-09.csv");
  });

  it("writes the details, the headings and one line per row", () => {
    const r = buildReport({ key: "k", name: "Add to Cart" }, [row, row], FROM, new Date(2026, 9, 9), "Designer Exchange (Admin)", NOW);
    const d = Object.fromEntries(r.meta);
    expect(d.Report).toBe("Add to Cart · daily results");
    expect(d.Period).toBe("07 Oct 2026 – 09 Oct 2026 (3 days)");
    expect(d.Generated).toBe("28 Oct 2026, 09:05:03");
    expect(d["Generated by"]).toBe("Designer Exchange (Admin)");
    expect(d.Rows).toBe("2");
    expect(r.rows[0]).toEqual(["2026-10-07", "Wed", "Add to Cart button text", "add-to-cart-btn", "control", "Add to Cart", 120, 12, "10.00", "added to cart"]);
  });

  it("says '1 day', not '1 days'", () => {
    expect(Object.fromEntries(buildReport({ key: "k", name: "A" }, [], FROM, TO, "x", NOW).meta).Period).toContain("(1 day)");
  });
});

describe("csvText", () => {
  it("starts with a byte-order mark so Excel reads £ and dashes", () => {
    const csv = csvText([["Price", "£520.00 – today"]]);
    expect(csv.charCodeAt(0)).toBe(0xfeff);
    expect(csv).toContain("£520.00 – today");
  });

  it("quotes every value, doubles inner quotes and ends lines with CRLF", () => {
    expect(csvText([["a", 'say "hi"'], ["b", 2]])).toBe('﻿"a","say ""hi"""\r\n"b","2"');
  });

  it("keeps a date as text, so it opens as 2026-10-07", () => {
    expect(csvText([["2026-10-07"]])).toContain('"2026-10-07"');
  });
});

describe("report rows from the data layer", () => {
  it("make a two-row-per-day report", async () => {
    vi.useFakeTimers();
    const p = getReportRows("add-to-cart", new Date(2026, 9, 7), new Date(2026, 9, 9));
    await vi.advanceTimersByTimeAsync(400);
    const rows = await p;
    vi.useRealTimers();
    expect(rows).toHaveLength(6);
    expect(buildReport({ key: "add-to-cart", name: "x" }, rows, new Date(2026, 9, 7), new Date(2026, 9, 9), "x", NOW).rows).toHaveLength(6);
  });
});
