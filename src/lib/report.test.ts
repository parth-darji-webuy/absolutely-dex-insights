import { describe, expect, it } from "vitest";
import { buildReport, csvText, reportCsv, safeFilePart } from "./report";
import type { ReportRow } from "@/types";

const row: ReportRow = { date: "2026-10-07", weekday: "Wed", experiment: "Add to Cart button text", flag: "add-to-cart-btn", variant: "control", label: "Add to Cart", people: 120, converted: 12, ratePct: "10.00", metric: "added to cart" };
const FROM = new Date(2026, 9, 7);
const TO = new Date(2026, 9, 7);
const NOW = new Date("2026-10-28T09:05:03Z");

describe("buildReport", () => {
  it("names the file after the experiment and the period, always with from and to", () => {
    expect(buildReport({ key: "add-to-cart", name: "Add to Cart" }, [row], FROM, TO, "x", "UTC", NOW).file).toBe("absolutelydex_add-to-cart-daily_2026-10-07_to_2026-10-07.csv");
    expect(buildReport({ key: "add-to-cart", name: "Add to Cart" }, [row], FROM, new Date(2026, 9, 9), "x", "UTC", NOW).file).toBe("absolutelydex_add-to-cart-daily_2026-10-07_to_2026-10-09.csv");
  });

  it("keeps odd characters out of the file name", () => {
    expect(safeFilePart('a/b"c d\r\n')).toBe("a-b-c-d");
    expect(safeFilePart("")).toBe("experiment");
    expect(buildReport({ key: '../x"y', name: "A" }, [], FROM, TO, "x", "UTC", NOW).file).toMatch(/^absolutelydex_[A-Za-z0-9._-]+-daily_2026-10-07_to_2026-10-07\.csv$/);
  });

  it("writes the details on the store's clock and time zone", () => {
    const r = buildReport({ key: "k", name: "Add to Cart" }, [row, row], FROM, new Date(2026, 9, 9), "Designer Exchange (Admin)", "Asia/Kolkata", NOW);
    const d = Object.fromEntries(r.meta);
    expect(d.Report).toBe("Add to Cart · daily results");
    expect(d.Period).toBe("07 Oct 2026 – 09 Oct 2026 (3 days)");
    expect(d.Generated).toBe("28 Oct 2026, 14:35:03");
    expect(d["Time zone"]).toBe("Asia/Kolkata (UTC+05:30)");
    expect(d["Generated by"]).toBe("Designer Exchange (Admin)");
    expect(d.Rows).toBe("2");
  });

  it("says UTC+00:00 for UTC and '1 day' for one day", () => {
    const r = buildReport({ key: "k", name: "A" }, [], FROM, TO, "x", "UTC", NOW);
    expect(Object.fromEntries(r.meta)["Time zone"]).toBe("UTC (UTC+00:00)");
    expect(Object.fromEntries(r.meta).Period).toContain("(1 day)");
  });
});

describe("csvText", () => {
  it("starts with a byte-order mark so Excel reads £ and dashes", () => {
    const csv = csvText([["Price", "£520.00 – today"]]);
    expect(csv.charCodeAt(0)).toBe(0xfeff);
    expect(csv).toContain("£520.00 – today");
  });

  it("quotes every value, doubles inner quotes and ends lines with CRLF only", () => {
    expect(csvText([["a", 'say "hi"'], ["b", 2]])).toBe('﻿"a","say ""hi"""\r\n"b","2"');
    expect(csvText([["a"], ["b"]])).not.toMatch(/[^\r]\n/);
  });

  it("keeps commas and line breaks inside a cell", () => {
    expect(csvText([["Add to Cart, then Buy Now", "line1\nline2"]])).toBe('﻿"Add to Cart, then Buy Now","line1\nline2"');
  });

  it("puts an apostrophe before a cell that starts with = + - or @", () => {
    expect(csvText([["=SUM(A1)", "+1", "-1", "@x", "a=b", " =x", "x@"]])).toBe('﻿"\'=SUM(A1)","\'+1","\'-1","\'@x","a=b"," =x","x@"');
    expect(csvText([['=HYPERLINK("http://x")']])).toBe('﻿"\'=HYPERLINK(""http://x"")"');
  });

  it("keeps a date as text, so it opens as 2026-10-07", () => {
    expect(csvText([["2026-10-07"]])).toContain('"2026-10-07"');
  });
});

describe("reportCsv", () => {
  it("is the details, a blank line, the header, then the rows", () => {
    const r = buildReport({ key: "k", name: "A" }, [row], FROM, TO, "x", "UTC", NOW);
    const lines = reportCsv(r).split("\r\n");
    expect(lines).toHaveLength(7 + 1 + 1 + 1);
    expect(lines[0]).toBe('﻿"Report","A · daily results"');
    expect(lines[7]).toBe("");
    expect(lines[8]).toBe('"date","weekday","experiment","flag","variant","label","people","converted","rate_pct","metric"');
    expect(lines[9]).toBe('"2026-10-07","Wed","Add to Cart button text","add-to-cart-btn","control","Add to Cart","120","12","10.00","added to cart"');
  });
});
