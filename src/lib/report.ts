import { daysBetween, niceDate, ymd } from "./dates";
import { stamp, tzLabel } from "./tz";
import type { ReportRow } from "@/types";

export const REPORT_HEAD = ["date", "weekday", "experiment", "flag", "variant", "label", "people", "converted", "rate_pct", "metric"];

export type ReportMeta = { key: string; name: string };
export type Report = { name: string; meta: string[][]; head: string[]; rows: (string | number)[][]; file: string };

/** Letters, digits, dot, dash and underscore only, so a key can never break out of a file name or a header. */
export const safeFilePart = (s: string): string => s.replace(/[^A-Za-z0-9._-]+/g, "-").replace(/^-+|-+$/g, "") || "experiment";

/** The details shown above the table, the column headers, the rows and the file name of one experiment's CSV. */
export function buildReport(exp: ReportMeta, rows: ReportRow[], from: Date, to: Date, generatedBy: string, tz: string, now: Date = new Date()): Report {
  const name = `${exp.name} · daily results`;
  const n = Math.max(0, daysBetween(from, to));
  const meta = [
    ["Report", name],
    ["Workspace", "AbsolutelyDeX Insights"],
    ["Period", `${niceDate(from)} – ${niceDate(to)} (${n} day${n === 1 ? "" : "s"})`],
    ["Generated", stamp(now, tz)],
    ["Time zone", tzLabel(now, tz)],
    ["Generated by", generatedBy],
    ["Rows", String(rows.length)],
  ];
  return {
    name,
    meta,
    head: REPORT_HEAD,
    rows: rows.map((r) => [r.date, r.weekday, r.experiment, r.flag, r.variant, r.label, r.people, r.converted, r.ratePct, r.metric]),
    file: `absolutelydex_${safeFilePart(exp.key)}-daily_${ymd(from)}_to_${ymd(to)}.csv`,
  };
}

/**
 * Every cell in quotes (inner quotes doubled), rows joined by CRLF, and a byte-order mark first so Excel reads
 * £, ’ and – correctly. A cell that starts with = + - or @ gets an apostrophe in front, so a spreadsheet can
 * never run it as a formula.
 */
export function csvText(lines: (string | number)[][]): string {
  const cell = (v: string | number) => {
    const text = String(v);
    return `"${(/^[=+\-@]/.test(text) ? "'" + text : text).replace(/"/g, '""')}"`;
  };
  return "﻿" + lines.map((r) => r.map(cell).join(",")).join("\r\n");
}

/** The whole file: details, a blank line, the header, then the rows. */
export const reportCsv = (r: Report): string => csvText([...r.meta, [], r.head, ...r.rows]);

/** Saves a file through the browser's download. */
export function downloadBlob(name: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
