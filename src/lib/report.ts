import { daysBetween, hms, niceDate, tzLabel, ymd } from "./dates";
import type { ReportRow } from "@/types";

export const REPORT_HEAD = ["date", "weekday", "experiment", "flag", "variant", "label", "people", "converted", "rate_pct", "metric"];

export type ReportMeta = { key: string; name: string };
export type Report = { name: string; meta: string[][]; head: string[]; rows: (string | number)[][]; file: string };

/** The details shown above the table, the column headers and the rows of one experiment's CSV. */
export function buildReport(exp: ReportMeta, rows: ReportRow[], from: Date, to: Date, generatedBy: string, now: Date = new Date()): Report {
  const name = `${exp.name} · daily results`;
  const n = Math.max(0, daysBetween(from, to));
  const period = `${niceDate(from)} – ${niceDate(to)} (${n} day${n === 1 ? "" : "s"})`;
  const meta = [
    ["Report", name],
    ["Workspace", "AbsolutelyDeX Insights"],
    ["Period", period],
    ["Generated", `${niceDate(now)}, ${hms(now)}`],
    ["Time zone", tzLabel(now)],
    ["Generated by", generatedBy],
    ["Rows", String(rows.length)],
  ];
  const span = ymd(from) === ymd(to) ? ymd(from) : `${ymd(from)}_to_${ymd(to)}`;
  return {
    name,
    meta,
    head: REPORT_HEAD,
    rows: rows.map((r) => [r.date, r.weekday, r.experiment, r.flag, r.variant, r.label, r.people, r.converted, r.ratePct, r.metric]),
    file: `absolutelydex_${exp.key}-daily_${span}.csv`,
  };
}

/** Every value in quotes, rows joined by CRLF, with a byte-order mark so Excel reads £, ’ and – correctly. */
export function csvText(lines: (string | number)[][]): string {
  const q = (v: string | number) => `"${String(v).replace(/"/g, '""')}"`;
  return "﻿" + lines.map((r) => r.map(q).join(",")).join("\r\n");
}

/** Saves a CSV through the browser's download. */
export function downloadCSV(name: string, lines: (string | number)[][]): void {
  const url = URL.createObjectURL(new Blob([csvText(lines)], { type: "text/csv;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
